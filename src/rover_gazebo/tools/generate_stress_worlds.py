#!/usr/bin/python3
"""Write the stress-test worlds into worlds/ (and their terrain files into worlds/terrain/).

    python3 tools/generate_stress_worlds.py            # from the package root

Every world here is generated, seeded and deterministic -- re-running this reproduces
them byte for byte, so do not hand-edit the .sdf files it writes. Each world is a set of
parallel lanes along +x, spaced in y, so one sim launch can test several conditions:
stability_test.py teleports the rover to each lane's start (the LANES table below is
mirrored there as STRESS_LANES). doc/STRESS_TESTING.md describes what each one is for.

"Realistic-hard" on purpose: everything here is something the real rover should be able
to drive over -- slopes up to 25 deg, rocks no taller than the 0.15 m wheel radius,
4 cm washboard, low but non-zero friction -- so a failure is a finding, not a foregone
conclusion.
"""

