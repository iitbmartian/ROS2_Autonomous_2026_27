COLOURS = {"orange": "0.75 0.45 0.2 1", "blue": "0.2 0.45 0.75 1",
           "rock": "0.45 0.40 0.35 1", "ice": "0.70 0.85 0.95 1",
           "green": "0.35 0.6 0.3 1", "red": "0.8 0.25 0.2 1"}


def f(*v):
    return " ".join(f"{x:.5f}" for x in v)


def model(name, pose, geom, colour="orange", mu=1.0):
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{f(*pose)}</pose>
      <link name="link">
        <collision name="collision">
          <geometry>{geom}</geometry>
          <surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry>{geom}</geometry>
          <material><ambient>{COLOURS[colour]}</ambient><diffuse>{COLOURS[colour]}</diffuse></material>
        </visual>
      </link>
    </model>"""


def box(size):
    return f"<box><size>{f(*size)}</size></box>"


def slab(name, x0, x1, y, width, z0, z1, colour="orange", mu=1.0, thick=0.4):
    """A box whose top face runs straight from (x0, z0) to (x1, z1) across `width`.
    Built from a pitched box, the way ledge.sdf's wedge is, so the surface is exact."""
    length = math.hypot(x1 - x0, z1 - z0)
    a = math.atan2(z1 - z0, x1 - x0)
    cx, cz = (x0 + x1) / 2 + thick / 2 * math.sin(a), (z0 + z1) / 2 - thick / 2 * math.cos(a)
    return model(name, (cx, y, cz, 0, -a, 0), box((length, width, thick)), colour, mu)


def tilted_strip(name, x0, x1, yc, width, roll, colour="blue", mu=1.0, thick=0.4):
    """A strip tilted about x (cross-slope), rising toward +y, low edge on the ground, so
    its centre line sits width/2*sin(roll) up. The rover is teleported onto it."""
    hc = width / 2 * math.sin(roll)
    cy = yc + thick / 2 * math.sin(roll)
    cz = hc - thick / 2 * math.cos(roll)
    return model(name, ((x0 + x1) / 2, cy, cz, roll, 0, 0),
                 box((x1 - x0, width, thick)), colour, mu)


# -- worlds ---------------------------------------------------------------------

def slopes():
    """Four lanes of up-ramp -> plateau -> down-ramp, 10/15/20/25 deg, 3 m ramps."""
    out, lanes = [], []
    for k, deg in enumerate((10, 15, 20, 25)):
        y, a = 4.0 * k, math.radians(deg)
        run = 3.0 * math.cos(a)
        h = 3.0 * math.sin(a)
        x0, x1, x2, x3 = 2.0, 2.0 + run, 2.0 + run + 3.0, 2.0 + 2 * run + 3.0
        out.append(slab(f"up_{deg}", x0, x1, y, 2.0, 0.0, h, "orange"))
        out.append(model(f"plateau_{deg}", ((x1 + x2) / 2, y, h - 0.2, 0, 0, 0),
                         box((x2 - x1 + 0.02, 2.0, 0.4)), "green"))
        out.append(slab(f"down_{deg}", x2, x3, y, 2.0, h, 0.0, "blue"))
        lanes.append((deg, y, h, x0, x1, x2, x3))
    doc = "\n".join(f"  lane y={y:4.1f}: {d:2d} deg, up x {x0:.2f}-{x1:.2f}, "
                    f"plateau {h:.2f} m high to x {x2:.2f}, down to x {x3:.2f}"
                    for d, y, h, x0, x1, x2, x3 in lanes)
    return "slopes", "  Ramps up, a 3 m plateau, ramps down. Approach from x=0.\n" + doc, out


def side_slope():
    """Two 12 m cross-slope strips, 12 and 18 deg; the rover is placed on the centre line."""
    # x from 2, not 0: the rover spawns at the origin, and rocker_coupling_node captures
    # its rest pose 2.5 s in -- spawned straddling a strip edge, it captured a twisted
    # pose (+12/+9/+17 deg) and held the suspension there all session.
    out = [tilted_strip("side_12", 2.0, 14.0, 0.0, 4.0, math.radians(12)),
           tilted_strip("side_18", 2.0, 14.0, 6.0, 4.0, math.radians(18), "orange")]
    doc = ("  4 m strips tilted about x, rising toward +y, low edge on the ground; the\n"
           "  centre line is 2*sin(roll) m up (0.416 m at 12 deg, 0.618 m at 18 deg).\n"
           "  lane y=0: 12 deg, lane y=6: 18 deg, x 2..14 (spawn at the origin stays flat).")
    return "side_slope", doc, out


def rocks(seed=7):
    """Seeded rock garden: a 12 m x 3 m corridor (y=0) and a denser 8 m one (y=5)."""
    rng = np.random.default_rng(seed)
    out = []
    for lane, (yc, n) in enumerate(((0.0, 45), (5.0, 70))):
        for i in range(n):
            x = rng.uniform(1.5, 13.5 if lane == 0 else 9.5)
            y = yc + rng.uniform(-1.3, 1.3)
            h = rng.uniform(0.03, 0.15)          # protrusion above ground, <= wheel radius
            kind = rng.integers(3)
            name = f"rock_{lane}_{i}"
            if kind == 0:                        # half-buried sphere
                r = rng.uniform(max(h, 0.06), 0.22)
                out.append(model(name, (x, y, h - r, 0, 0, 0),
                                 f"<sphere><radius>{r:.4f}</radius></sphere>", "rock"))
            else:                                # tilted block
                sx, sy = rng.uniform(0.08, 0.35), rng.uniform(0.08, 0.35)
                roll, pitch = rng.uniform(-0.3, 0.3, 2)
                out.append(model(name, (x, y, h / 2 - 0.02, roll, pitch, rng.uniform(0, math.pi)),
                                 box((sx, sy, h + 0.04)), "rock"))
    doc = ("  Seeded (7) scatter of half-buried spheres and tilted blocks, 3-15 cm\n"
           "  proud of the ground. lane y=0: 45 rocks over x 1.5..13.5;\n"
           "  lane y=5: 70 rocks over x 1.5..9.5 (dense).")
    return "rocks", doc, out


def washboard():
    """4 cm bumps (cylinders half-sunk) across the lane at 0.25 m and 0.40 m pitch."""
    out = []
    for lane, (yc, pitch) in enumerate(((0.0, 0.25), (4.0, 0.40))):
        x, i = 2.0, 0
        while x < 12.0:
            out.append(model(f"wb_{lane}_{i}", (x, yc, 0.0, math.pi / 2, 0, 0),
                             "<cylinder><radius>0.04</radius><length>2.0</length></cylinder>",
                             "orange" if lane == 0 else "blue"))
            x, i = x + pitch, i + 1
    doc = ("  Half-sunk 4 cm-radius bars across the lane, x 2..12.\n"
           "  lane y=0: 0.25 m pitch; lane y=4: 0.40 m pitch.")
    return "washboard", doc, out


def low_friction():
    """Uniform mu 0.3 patch; split-mu (0.2 left / 1.0 right); a 15 deg ramp at mu 0.5."""
    t = 0.01   # 1 cm slabs: a step far below anything the wheel notices
    out = [model("patch_mu03", (7.0, 0.0, t / 2, 0, 0, 0), box((10.0, 2.0, t)), "ice", 0.3),
           model("split_left_mu02", (7.0, 4.5, t / 2, 0, 0, 0), box((10.0, 1.0, t)), "ice", 0.2),
           model("split_right_mu1", (7.0, 3.5, t / 2, 0, 0, 0), box((10.0, 1.0, t)), "green", 1.0)]
    a = math.radians(15)
    run, h = 3.0 * math.cos(a), 3.0 * math.sin(a)
    out.append(slab("ramp_mu05", 2.0, 2.0 + run, 8.0, 2.0, 0.0, h, "ice", 0.5))
    out.append(model("ramp_mu05_top", (2.0 + run + 1.5, 8.0, h - 0.2, 0, 0, 0),
                     box((3.02, 2.0, 0.4)), "ice", 0.5))
    doc = ("  lane y=0: mu 0.3 slab x 2..12.  lane y=4: split mu, left wheels (y>4) on\n"
           "  mu 0.2, right on mu 1.0, x 2..12.  lane y=8: 15 deg ramp at mu 0.5 from x=2.\n"
           "  DART takes the lower of the two surfaces' mu; the wheels are mu 1.0.")
    return "low_friction", doc, out


def rough_terrain(seed=11, n=129, size=20.0, amp=0.10, as_mesh=True):
    """Fractal-noise terrain, +-amp about its own mean, tapered to zero at the edges so
    it meets the ground plane. Written as an OBJ trimesh (DART-safe collision) or a PNG
    heightmap; the rover starts on flat ground at x=0 and drives into it at x=2."""
    rng = np.random.default_rng(seed)
    hgt = np.zeros((n, n))
    for octave in range(1, 6):                       # sum of upsampled random grids
        k = 2 ** octave + 1
        grid = rng.standard_normal((k, k))
        xs = np.linspace(0, k - 1, n)
        rows = np.array([np.interp(xs, np.arange(k), g) for g in grid])
        up = np.array([np.interp(xs, np.arange(k), c) for c in rows.T]).T
        hgt += up / octave ** 1.2
    hgt -= hgt.min()
    hgt *= 2 * amp / hgt.max()
    u = np.linspace(0, 1, n)
    taper = np.minimum(1, np.minimum(u, 1 - u) / 0.12)
    hgt *= np.outer(taper, taper)                    # 0 at the border
    xs = np.linspace(0, size, n) + 2.0               # x from 2 to 22
    ys = np.linspace(-size / 2, size / 2, n)
    os.makedirs(os.path.join(WORLDS, "terrain"), exist_ok=True)
    path = os.path.join(WORLDS, "terrain", "rough.obj")
    # Per-vertex normals are not optional: without them gz-physics' DART mesh loader
    # drops the submesh and the ODE collision detector then segfaults the whole sim.
    dzdx, dzdy = np.gradient(hgt, xs, ys)
    nrm = np.stack([-dzdx, -dzdy, np.ones_like(hgt)], -1)
    nrm /= np.linalg.norm(nrm, axis=-1, keepdims=True)
    with open(path, "w") as fh:
        fh.write("# GENERATED by tools/generate_stress_worlds.py\n")
        for i in range(n):            # i indexes x, j indexes y
            for j in range(n):
                fh.write(f"v {xs[i]:.4f} {ys[j]:.4f} {hgt[i, j]:.4f}\n")
        for i in range(n):
            for j in range(n):
                fh.write("vn %.4f %.4f %.4f\n" % tuple(nrm[i, j]))
        for i in range(n - 1):
            for j in range(n - 1):
                a, b = i * n + j + 1, (i + 1) * n + j + 1
                fh.write(f"f {a}//{a} {b}//{b} {b + 1}//{b + 1}\n"
                         f"f {a}//{a} {b + 1}//{b + 1} {a + 1}//{a + 1}\n")
    geom = f"<mesh><uri>{TERRAIN_URI}/rough.obj</uri></mesh>"
    out = [model("rough_terrain", (0, 0, 0, 0, 0, 0), geom, "rock")]
    doc = (f"  Seeded ({seed}) fractal heightfield, 0..{2 * amp:.2f} m, x 2..22, y -10..10,\n"
           "  tapered to ground level at its edges. Collision is the OBJ trimesh in\n"
           "  worlds/terrain/rough.obj. Start at x=0 and drive in along any lane.")
    return "rough_terrain", doc, out


def main():
    for build in (slopes, side_slope, rocks, washboard, low_friction, rough_terrain):
        name, doc, models = build()
        path = os.path.join(WORLDS, f"{name}.sdf")
        with open(path, "w") as fh:
            fh.write(HEADER.format(name=name, doc=doc))
            fh.write("".join(models))
            fh.write(FOOTER)
        print(f"wrote {os.path.relpath(path)} ({len(models)} models)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
