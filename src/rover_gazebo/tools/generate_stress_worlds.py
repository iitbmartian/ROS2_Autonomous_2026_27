import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.realpath(__file__))   # through the install symlink
WORLDS = os.path.join(HERE, "..", "worlds")
TERRAIN_URI = "model://rover_gazebo/worlds/terrain"

